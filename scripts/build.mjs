// Builds the static site into dist/.
//   public/*        -> dist/*            (the arcade shell)
//   games/*.html    -> dist/games/<id>.html  (with the arcade bridge injected)
//   env + manifest  -> dist/config.js
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseEnv, parsePlayers, parseBool, htmlTitle, injectBridge, buildManifest } from './lib.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'dist');
const GAMES = path.join(ROOT, 'games');
const PUBLIC = path.join(ROOT, 'public');

async function loadEnv() {
  // Real environment (Vercel) wins over the local .env file.
  let fileEnv = {};
  try { fileEnv = parseEnv(await fs.readFile(path.join(ROOT, '.env'), 'utf8')); } catch { /* no .env */ }
  return { ...fileEnv, ...process.env };
}

async function main() {
  const env = await loadEnv();
  await fs.rm(DIST, { recursive: true, force: true });
  await fs.mkdir(path.join(DIST, 'games'), { recursive: true });
  await fs.cp(PUBLIC, DIST, { recursive: true });

  let meta = [];
  try {
    meta = JSON.parse(await fs.readFile(path.join(GAMES, 'games.json'), 'utf8'));
    if (!Array.isArray(meta)) throw new Error('games.json must be an array');
  } catch (e) {
    if (e.code !== 'ENOENT') throw new Error(`games/games.json is invalid: ${e.message}`);
  }

  const files = (await fs.readdir(GAMES)).filter((f) => /\.html?$/i.test(f)).sort();
  const sources = new Map();
  for (const f of files) sources.set(f, await fs.readFile(path.join(GAMES, f), 'utf8'));

  const { games, warnings } = buildManifest(meta, files, (f) => htmlTitle(sources.get(f) || ''));
  for (const w of warnings) console.warn(`  ! ${w}`);

  for (const g of games) {
    await fs.writeFile(path.join(DIST, g.path), injectBridge(sources.get(g.file)));
  }

  const config = {
    siteName: env.PUBLIC_SITE_NAME || 'Super Games Arcade',
    players: parsePlayers(env.PUBLIC_PLAYERS),
    analytics: parseBool(env.PUBLIC_ENABLE_VERCEL_ANALYTICS),
    buildId: Date.now().toString(36),
    games: games.map(({ file, ...pub }) => pub), // source filenames stay private
  };
  await fs.writeFile(
    path.join(DIST, 'config.js'),
    `// Generated by scripts/build.mjs — do not edit.\nwindow.ARCADE_CONFIG = ${JSON.stringify(config, null, 2)};\n`,
  );

  // Site name also goes into the web app manifest + <title>.
  const manifestPath = path.join(DIST, 'manifest.webmanifest');
  const manifest = JSON.parse(await fs.readFile(manifestPath, 'utf8'));
  manifest.name = config.siteName;
  manifest.short_name = config.siteName.length > 12 ? config.siteName.split(' ').slice(0, 2).join(' ') : config.siteName;
  await fs.writeFile(manifestPath, JSON.stringify(manifest, null, 2));
  const indexPath = path.join(DIST, 'index.html');
  const index = await fs.readFile(indexPath, 'utf8');
  const safeName = config.siteName.replace(/[<>&"]/g, '');
  await fs.writeFile(indexPath, index.replaceAll('Super Games Arcade', safeName));

  console.log(`Built ${games.length} game(s) into dist/: ${games.map((g) => g.id).join(', ')}`);
  console.log(`Players: ${config.players.length ? config.players.map((p) => p.name).join(', ') : '(profiles off)'}`);
}

main().catch((e) => { console.error(e); process.exit(1); });
